@dataclass
class BLLDesign:
    """Cached SVD of frozen features, avoiding unstable normal equations."""
    singular_values: torch.Tensor
    right_vectors: torch.Tensor
    projected_targets: torch.Tensor
    residual_squared: torch.Tensor
    n: int
    h: int


@dataclass
class SpectralPrecision:
    right_vectors: torch.Tensor
    eigenvalues: torch.Tensor

    @property
    def dtype(self):
        return self.eigenvalues.dtype

    @property
    def device(self):
        return self.eigenvalues.device


@torch.no_grad()
def prepare_bll_design(phi, y):
    x = phi.double()
    y = y.reshape(-1, 1).to(device=x.device, dtype=x.dtype)
    if not torch.isfinite(x).all() or not torch.isfinite(y).all():
        raise ValueError("BLL features or targets contain non-finite values.")
    u, singular, vh = torch.linalg.svd(x, full_matrices=x.shape[0] < x.shape[1])
    # Treat singular values below the SVD's numerical resolution as zero.
    # Otherwise roundoff in exactly duplicate columns can create large weights.
    tolerance = torch.finfo(x.dtype).eps * max(x.shape) * singular.max()
    singular = torch.where(singular > tolerance, singular, torch.zeros_like(singular))
    projected = u.T @ y
    residual = (y - u @ projected).square().sum()
    if x.shape[0] < x.shape[1]:
        nullity = x.shape[1] - x.shape[0]
        singular = torch.cat([singular, singular.new_zeros(nullity)])
        projected = torch.cat([projected, projected.new_zeros(nullity, 1)])
    return BLLDesign(singular, vh.T, projected, residual, *x.shape)


def _spectral_posterior(design, sigma_p2, alpha0, beta0):
    s = design.singular_values
    sigma = torch.as_tensor(sigma_p2, dtype=s.dtype, device=s.device)
    ridge = sigma.reciprocal()
    eigenvalues = s.square() + ridge
    coefficients = s[:, None] * design.projected_targets / eigenvalues[:, None]
    mean = design.right_vectors @ coefficients
    quad = design.residual_squared + (
        ridge / eigenvalues * design.projected_targets.squeeze(1).square()
    ).sum()
    alpha = torch.as_tensor(alpha0 + .5 * design.n, dtype=s.dtype, device=s.device)
    beta = (torch.as_tensor(beta0, dtype=s.dtype, device=s.device) + .5 * quad).clamp_min(1e-12)
    return mean, SpectralPrecision(design.right_vectors, eigenvalues), alpha, beta


def nig_nll_feature(a, y, log_sigma_p2, alpha0=0.0, beta0=0.0):
    if isinstance(a, BLLDesign):
        log_sigma = log_sigma_p2.to(a.singular_values)
        _, precision, alpha, beta = _spectral_posterior(a, log_sigma.exp(), alpha0, beta0)
        logdet0 = -a.h * log_sigma
        logdetn = precision.eigenvalues.log().sum()
        return -(torch.lgamma(alpha) - alpha * beta.log()
                 + .5 * (logdet0 - logdetn) - .5 * a.n * np.log(2 * np.pi))
    device = a.device
    dtype = a.dtype
    n, h = a.shape

    a0 = torch.as_tensor(alpha0, dtype=dtype, device=device)
    b0 = torch.as_tensor(beta0, dtype=dtype, device=device)
    sigma_p2 = torch.exp(log_sigma_p2.to(dtype=dtype, device=device))
    y_col = y.view(-1, 1).to(device, dtype)

    lambda0 = (1.0 / sigma_p2) * torch.eye(h, device=device, dtype=dtype)
    lambda_n = a.T @ a + lambda0

    _, logdet0 = torch.linalg.slogdet(lambda0)
    _, logdetn = torch.linalg.slogdet(lambda_n)

    mu_n = torch.linalg.solve(lambda_n, a.T @ y_col)

    y_ty = (y_col.T @ y_col).squeeze()
    mu_term = (mu_n.T @ (lambda_n @ mu_n)).squeeze()

    a_n = a0 + 0.5 * n
    # Avoid subtracting two large, nearly equal terms in high-precision runs.
    quad = ((y_col - a @ mu_n).square().sum() + mu_n.square().sum() / sigma_p2
            if dtype == torch.float64 else y_ty - mu_term)
    b_n = (b0 + 0.5 * quad).clamp_min(1e-12)

    log_marg = (
        torch.lgamma(a_n)
        - a_n * torch.log(b_n)
        + 0.5 * (logdet0 - logdetn)
        - 0.5 * n * torch.log(torch.tensor(2.0 * torch.pi, dtype=dtype, device=device))
    )
    return -log_marg


@torch.no_grad()
def compute_bll_posterior(phi_train, y_train, sigma_p2, alpha0, beta0):
    if isinstance(phi_train, BLLDesign):
        mean, precision, alpha, beta = _spectral_posterior(phi_train, sigma_p2, alpha0, beta0)
        return mean, precision, alpha.clamp_min(1.0 + 1e-6), beta
    dtype, device = phi_train.dtype, phi_train.device
    y_train = y_train.to(device=device, dtype=dtype)
    sigma_p2 = torch.as_tensor(sigma_p2, device=device, dtype=dtype)
    h = phi_train.shape[1]
    precision = phi_train.T @ phi_train + (1.0 / sigma_p2) * torch.eye(h, device=device, dtype=dtype)
    rhs = phi_train.T @ y_train.view(-1, 1)
    m_n = torch.linalg.solve(precision, rhs)

    y = y_train.view(-1, 1)
    y_ty = (y.T @ y).squeeze()
    m_t_rhs = (m_n.T @ rhs).squeeze()
    quad = ((y - phi_train @ m_n).square().sum() + m_n.square().sum() / sigma_p2
            if dtype == torch.float64 else (y_ty - m_t_rhs).clamp_min(0.0))

    n = y_train.shape[0]
    alpha_n = torch.tensor(alpha0 + 0.5 * n, device=device, dtype=dtype).clamp_min(1.0 + 1e-6)
    beta_n = (torch.tensor(beta0, device=device, dtype=dtype) + 0.5 * quad).clamp_min(1e-12)
    return m_n, precision, alpha_n, beta_n


def _predictive_parameter_variance(phi, precision):
    """Compute phi P^-1 phi^T as a sum of squares, without hiding bad P."""
    if isinstance(precision, SpectralPrecision):
        if (not torch.isfinite(phi).all() or not torch.isfinite(precision.eigenvalues).all()
                or not (precision.eigenvalues > 0).all()):
            raise ValueError("Non-finite features or invalid spectral BLL precision.")
        return ((phi @ precision.right_vectors) / precision.eigenvalues.sqrt()).square().sum(1)
    if not torch.isfinite(phi).all() or not torch.isfinite(precision).all():
        raise ValueError("BLL features or precision contain non-finite values.")
    factor, info = torch.linalg.cholesky_ex(precision)
    if info.item() != 0:
        raise ValueError(
            "BLL precision is not positive definite. Recompute stage 2 with "
            "bll_dtype='float64'; do not clamp invalid predictive variances."
        )
    solved = torch.linalg.solve_triangular(factor, phi.T, upper=False)
    return solved.square().sum(dim=0)


@torch.no_grad()
def student_t_pred(phi, y_true_raw, m_n, precision, alpha_n, beta_n, y_mean, y_std):
    phi = phi.to(dtype=precision.dtype, device=precision.device)
    dof = 2 * alpha_n
    correction_ratio = ((dof - 2.0) / dof).clamp_min(1e-6)

    mean = (phi @ m_n).squeeze(1)
    param_var = _predictive_parameter_variance(phi, precision)
    u_var = (beta_n / (alpha_n - 1.0)) * (1.0 + param_var)
    scale = torch.sqrt(u_var * correction_ratio).clamp_min(1e-12)

    mean_raw = mean * y_std + y_mean
    var_raw = (scale**2) * (y_std**2)
    scale_raw = torch.sqrt(var_raw).clamp_min(1e-12)

    rmse = torch.sqrt(torch.mean((mean_raw - y_true_raw.squeeze()) ** 2)).item()
    nll = -StudentT(df=dof, loc=mean_raw, scale=scale_raw).log_prob(y_true_raw.squeeze()).mean().item()
    return rmse, nll, mean_raw, scale_raw


@torch.no_grad()
def bll_student_t_mu_lo_hi(phi_x, m_n, precision_beta, alpha_n, beta_n):
    phi_x = phi_x.to(dtype=precision_beta.dtype, device=precision_beta.device)
    mu = (phi_x @ m_n).squeeze(1)
    param_var = _predictive_parameter_variance(phi_x, precision_beta)

    dof = 2.0 * alpha_n
    correction_ratio = ((dof - 2.0) / dof).clamp_min(1e-6)
    var = (beta_n / (alpha_n - 1.0)) * (1.0 + param_var)
    scale = torch.sqrt(var * correction_ratio).clamp_min(1e-12)

    t_q975 = float(student_t_dist.ppf(0.975, df=float(dof.detach().cpu().item())))
    lo = mu - t_q975 * scale
    hi = mu + t_q975 * scale
    return mu, lo, hi


def optimize_sigma_p2_for_epoch_eval(
    phi_train: torch.Tensor,
    y_train: torch.Tensor,
    beta_var_prior: float,
    alpha0: float,
    beta0: float,
    learning_rate_step2: float,
    n_epochs_step2: int,
) -> torch.Tensor:
    log_sigma_p2 = nn.Parameter(
        torch.tensor(np.log(beta_var_prior), device=phi_train.device, dtype=phi_train.dtype)
    )
    step2_opt = optim.Adam([log_sigma_p2], lr=learning_rate_step2)
    design = prepare_bll_design(phi_train, y_train) if phi_train.dtype == torch.float64 else phi_train

    for _ in range(max(1, int(n_epochs_step2))):
        step2_opt.zero_grad()
        loss_total = nig_nll_feature(design, y_train, log_sigma_p2, alpha0=alpha0, beta0=beta0)
        loss_total.backward()
        step2_opt.step()

    return torch.exp(log_sigma_p2).detach()


def _iter_head_batches(x_train: torch.Tensor, y_train: torch.Tensor, n_nets: int, batch_size: int):
    n_train = x_train.shape[0]
    permutations = torch.stack([torch.randperm(n_train, device=x_train.device) for _ in range(n_nets)], dim=0)
    y_flat = y_train.squeeze(-1)
    for start in range(0, n_train, batch_size):
        stop = min(start + batch_size, n_train)
        batch_indices = permutations[:, start:stop]
        yield x_train[batch_indices], y_flat[batch_indices]


