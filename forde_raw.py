def gradient_repulsive_kde(gradients, bandwidth_floor=1e-6, normalization_eps=1e-8):
    """Return the original KDE penalty applied to raw input derivatives.

    Input: H x B x D unnormalized gradients. For D=1 the entire B-point field
    becomes a single vector, giving effective location count P=1. Otherwise
    P=B. FoRDE does not use Function_WGD's global median/log(H+1) heuristic.
    """
    _, bandwidth_floor, normalization_eps = validate_settings(0, bandwidth_floor, normalization_eps)
    if gradients.ndim != 3 or min(gradients.shape) < 1 or not gradients.is_floating_point():
        raise ValueError("gradients must be a floating tensor with nonempty shape (networks, points, features)")
    if not torch.isfinite(gradients).all():
        raise FloatingPointError("Nonfinite input gradients in FoRDE")
    members = gradients.shape[0]
    if gradients.shape[-1] == 1:
        gradients = gradients.reshape(members, 1, -1)
    # The sole mathematical ablation: keep raw derivatives, including magnitude.
    # The D=1 reshape above is retained, so the complete sampled slope field is
    # still one particle location. No division by norm, variance, or std occurs.
    normalized = gradients
    locations = normalized.shape[1]
    if members == 1:
        return normalized[0, 0, 0] * 0, normalized.new_full((1, locations), bandwidth_floor), normalized.new_zeros(())
    distances = (normalized[:, None] - normalized.detach()[None]).square().sum(-1)
    bandwidth = (
        torch.quantile(distances.detach(), .5, dim=0) / math.log(members)
    ).clamp_min(bandwidth_floor)
    regularizer = (
        torch.logsumexp((-distances / bandwidth).flatten(1), dim=1) - math.log(locations)
    ).sum() / locations
    pair_mask = torch.triu(torch.ones(members, members, dtype=torch.bool, device=gradients.device), diagonal=1)
    mean_distance = distances.detach()[pair_mask].sqrt().mean()
    if not torch.isfinite(regularizer):
        raise FloatingPointError("Nonfinite FoRDE kernel objective")
    return regularizer, bandwidth, mean_distance


def mean_input_gradients(ensemble, common_x):
    """Shared ordered points, separate graph per head, no input-gradient leakage."""
    points = common_x.detach().clone().requires_grad_(True)
    previous_modes = [(module, module.training) for module in ensemble.modules()]
    previous_buffers = [(module, name, buffer) for module in ensemble.modules()
                        for name, buffer in module._buffers.items() if buffer is not None]
    try:
        # The original vectorized BatchNorm updates running statistics with a
        # live graph. Evaluation statistics must be constants for this auxiliary
        # derivative pass, otherwise its backward revisits earlier minibatches.
        # Snapshot rather than mutate/detach originals: preserve baseline state
        # and give autograd stable values even after subsequent buffer updates.
        for module, name, buffer in previous_buffers:
            module._buffers[name] = buffer.detach().clone()
        ensemble.eval()
        means, _ = ensemble(points)
        return torch.stack([
            torch.autograd.grad(means[head].sum(), points, create_graph=True, retain_graph=True)[0]
            for head in range(ensemble.n_nets)
        ])
    finally:
        for module, name, buffer in previous_buffers:
            module._buffers[name] = buffer
        for module, training in previous_modes:
            module.training = training


def stage1_objective(ensemble, batch_x, batch_y, strength=0.001,
                     bandwidth_floor=1e-6, normalization_eps=1e-8, repulsion_x=None):
    strength, bandwidth_floor, normalization_eps = validate_settings(strength, bandwidth_floor, normalization_eps)
    mu, var = ensemble(batch_x)
    per_head_losses = gaussian_nll_batched(mu, var, batch_y)
    likelihood = per_head_losses.sum()
    regularizer = likelihood.new_zeros(())
    bandwidth = likelihood.new_zeros(())
    mean_distance = likelihood.new_zeros(())
    objective = likelihood
    if strength > 0 and ensemble.n_nets > 1:
        regularizer, bandwidths, mean_distance = gradient_repulsive_kde(
            mean_input_gradients(ensemble, batch_x[0] if repulsion_x is None else repulsion_x), bandwidth_floor, normalization_eps
        )
        bandwidth = bandwidths.mean()
        objective = likelihood + strength * regularizer
    if not torch.isfinite(objective):
        raise FloatingPointError("Nonfinite FoRDE stage-1 objective")
    diagnostics = torch.stack((likelihood.detach(), regularizer.detach(), objective.detach(),
                               bandwidth.detach(), mean_distance.detach()))
    return objective, per_head_losses, diagnostics



