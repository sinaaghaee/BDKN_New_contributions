def _activation_forward(name: str, x: torch.Tensor) -> torch.Tensor:
    if name == "ReLU":
        return F.relu(x)
    if name == "LeakyReLU":
        return F.leaky_relu(x)
    if name == "GELU":
        return F.gelu(x)
    if name == "SiLU":
        return F.silu(x)
    if name == "Tanh":
        return torch.tanh(x)
    raise ValueError(f"Unknown activation '{name}'")


@dataclass
class SingleHeadSpec:
    input_dim: int
    hidden_dim: int
    hidden_layers: int
    activation_name: str
    norm_type: str
    jitter_eps: float


class StandaloneSingleHeadNetwork(nn.Module):
    def __init__(self, spec: SingleHeadSpec):
        super().__init__()
        self.spec = spec
        self.layers = nn.ModuleList()
        self.norms = nn.ModuleList()

        self.layers.append(nn.Linear(spec.input_dim, spec.hidden_dim))
        self.norms.append(self._make_norm(spec))
        for _ in range(spec.hidden_layers - 1):
            self.layers.append(nn.Linear(spec.hidden_dim, spec.hidden_dim))
            self.norms.append(self._make_norm(spec))
        self.out = nn.Linear(spec.hidden_dim, 2)

    @staticmethod
    def _make_norm(spec: SingleHeadSpec):
        if spec.norm_type == "none":
            return None
        if spec.norm_type == "layer":
            return nn.LayerNorm(spec.hidden_dim)
        if spec.norm_type == "batch":
            return nn.BatchNorm1d(spec.hidden_dim)
        raise ValueError(f"Unknown norm_type '{spec.norm_type}'")

    def forward(self, x: torch.Tensor):
        out = x
        for linear, norm in zip(self.layers, self.norms):
            out = linear(out)
            if norm is not None:
                out = norm(out)
            out = _activation_forward(self.spec.activation_name, out)
        raw = self.out(out)
        mu_raw = raw[..., 0]
        var_raw = raw[..., 1]
        var = F.softplus(var_raw) + float(self.spec.jitter_eps)
        return mu_raw, var


class BatchedSingleHeadEnsemble(nn.Module):
    def __init__(
        self,
        n_nets: int,
        spec: SingleHeadSpec,
        batch_norm_eps: float = 1e-5,
        batch_norm_momentum: float = 0.1,
    ):
        super().__init__()
        self.n_nets = int(n_nets)
        self.spec = spec
        self.batch_norm_eps = float(batch_norm_eps)
        self.batch_norm_momentum = float(batch_norm_momentum)

        hidden_dim = int(spec.hidden_dim)
        input_dim = int(spec.input_dim)
        hidden_layers = int(spec.hidden_layers)

        self.input_weight = nn.Parameter(torch.empty(self.n_nets, input_dim, hidden_dim))
        self.input_bias = nn.Parameter(torch.empty(self.n_nets, hidden_dim))
        self.hidden_weights = nn.ParameterList(
            [nn.Parameter(torch.empty(self.n_nets, hidden_dim, hidden_dim)) for _ in range(max(hidden_layers - 1, 0))]
        )
        self.hidden_biases = nn.ParameterList(
            [nn.Parameter(torch.empty(self.n_nets, hidden_dim)) for _ in range(max(hidden_layers - 1, 0))]
        )
        self.output_weight = nn.Parameter(torch.empty(self.n_nets, hidden_dim, 2))
        self.output_bias = nn.Parameter(torch.empty(self.n_nets, 2))

        self.layer_norm_weights = nn.ParameterList()
        self.layer_norm_biases = nn.ParameterList()
        self.batch_norm_weights = nn.ParameterList()
        self.batch_norm_biases = nn.ParameterList()
        self.n_norm_layers = hidden_layers if spec.norm_type != "none" else 0

        if spec.norm_type == "layer":
            for _ in range(self.n_norm_layers):
                self.layer_norm_weights.append(nn.Parameter(torch.ones(self.n_nets, hidden_dim)))
                self.layer_norm_biases.append(nn.Parameter(torch.zeros(self.n_nets, hidden_dim)))
        elif spec.norm_type == "batch":
            for layer_idx in range(self.n_norm_layers):
                self.batch_norm_weights.append(nn.Parameter(torch.ones(self.n_nets, hidden_dim)))
                self.batch_norm_biases.append(nn.Parameter(torch.zeros(self.n_nets, hidden_dim)))
                self.register_buffer(f"batch_running_mean_{layer_idx}", torch.zeros(self.n_nets, hidden_dim))
                self.register_buffer(f"batch_running_var_{layer_idx}", torch.ones(self.n_nets, hidden_dim))
                self.register_buffer(f"batch_num_batches_tracked_{layer_idx}", torch.zeros(self.n_nets, dtype=torch.long))

    @classmethod
    def from_reference_models(cls, reference_models: list[StandaloneSingleHeadNetwork]) -> "BatchedSingleHeadEnsemble":
        if not reference_models:
            raise ValueError("reference_models must be non-empty")
        first = reference_models[0]
        spec = first.spec
        model = cls(n_nets=len(reference_models), spec=spec).to(next(first.parameters()).device)
        with torch.no_grad():
            model.input_weight.copy_(torch.stack([net.layers[0].weight.T for net in reference_models], dim=0))
            model.input_bias.copy_(torch.stack([net.layers[0].bias for net in reference_models], dim=0))
            for hidden_idx, layer in enumerate(range(1, len(first.layers))):
                model.hidden_weights[hidden_idx].copy_(
                    torch.stack([net.layers[layer].weight.T for net in reference_models], dim=0)
                )
                model.hidden_biases[hidden_idx].copy_(
                    torch.stack([net.layers[layer].bias for net in reference_models], dim=0)
                )
            model.output_weight.copy_(torch.stack([net.out.weight.T for net in reference_models], dim=0))
            model.output_bias.copy_(torch.stack([net.out.bias for net in reference_models], dim=0))

            if spec.norm_type == "layer":
                for norm_idx in range(model.n_norm_layers):
                    model.layer_norm_weights[norm_idx].copy_(
                        torch.stack([net.norms[norm_idx].weight for net in reference_models], dim=0)
                    )
                    model.layer_norm_biases[norm_idx].copy_(
                        torch.stack([net.norms[norm_idx].bias for net in reference_models], dim=0)
                    )
            elif spec.norm_type == "batch":
                for norm_idx in range(model.n_norm_layers):
                    model.batch_norm_weights[norm_idx].copy_(
                        torch.stack([net.norms[norm_idx].weight for net in reference_models], dim=0)
                    )
                    model.batch_norm_biases[norm_idx].copy_(
                        torch.stack([net.norms[norm_idx].bias for net in reference_models], dim=0)
                    )
                    getattr(model, f"batch_running_mean_{norm_idx}").copy_(
                        torch.stack([net.norms[norm_idx].running_mean for net in reference_models], dim=0)
                    )
                    getattr(model, f"batch_running_var_{norm_idx}").copy_(
                        torch.stack([net.norms[norm_idx].running_var for net in reference_models], dim=0)
                    )
                    getattr(model, f"batch_num_batches_tracked_{norm_idx}").copy_(
                        torch.stack([net.norms[norm_idx].num_batches_tracked for net in reference_models], dim=0)
                    )
        return model

    @classmethod
    def from_artifact(cls, artifact: dict, device: torch.device) -> "BatchedSingleHeadEnsemble":
        spec = SingleHeadSpec(**artifact["spec"])
        model = cls(n_nets=int(artifact["n_nets"]), spec=spec).to(device)
        model.load_state_dict(artifact["state_dict"])
        return model

    def _apply_norm(self, x: torch.Tensor, layer_idx: int) -> torch.Tensor:
        if self.spec.norm_type == "none":
            return x
        if self.spec.norm_type == "layer":
            mean = x.mean(dim=-1, keepdim=True)
            var = x.var(dim=-1, keepdim=True, unbiased=False)
            x_hat = (x - mean) / torch.sqrt(var + self.batch_norm_eps)
            return x_hat * self.layer_norm_weights[layer_idx].unsqueeze(1) + self.layer_norm_biases[layer_idx].unsqueeze(1)
        if self.spec.norm_type == "batch":
            running_mean = getattr(self, f"batch_running_mean_{layer_idx}")
            running_var = getattr(self, f"batch_running_var_{layer_idx}")
            tracked = getattr(self, f"batch_num_batches_tracked_{layer_idx}")
            if self.training:
                batch_mean = x.mean(dim=1)
                batch_var = x.var(dim=1, unbiased=False)
                running_mean.mul_(1.0 - self.batch_norm_momentum).add_(self.batch_norm_momentum * batch_mean)
                running_var.mul_(1.0 - self.batch_norm_momentum).add_(self.batch_norm_momentum * batch_var)
                tracked.add_(1)
                mean = batch_mean.unsqueeze(1)
                var = batch_var.unsqueeze(1)
            else:
                mean = running_mean.unsqueeze(1)
                var = running_var.unsqueeze(1)
            x_hat = (x - mean) / torch.sqrt(var + self.batch_norm_eps)
            return x_hat * self.batch_norm_weights[layer_idx].unsqueeze(1) + self.batch_norm_biases[layer_idx].unsqueeze(1)
        raise ValueError(f"Unknown norm_type '{self.spec.norm_type}'")

    def forward(self, x: torch.Tensor):
        if x.dim() == 2:
            xh = x.unsqueeze(0).expand(self.n_nets, -1, -1)
        elif x.dim() == 3:
            if x.shape[0] != self.n_nets:
                raise ValueError(f"Expected first dim to be n_nets={self.n_nets}, got {tuple(x.shape)}")
            xh = x
        else:
            raise ValueError(f"Expected 2D or 3D input, got shape {tuple(x.shape)}")

        out = torch.einsum("hbi,hio->hbo", xh, self.input_weight) + self.input_bias.unsqueeze(1)
        if self.n_norm_layers > 0:
            out = self._apply_norm(out, 0)
        out = _activation_forward(self.spec.activation_name, out)

        for layer_idx, (weight, bias) in enumerate(zip(self.hidden_weights, self.hidden_biases), start=1):
            out = torch.einsum("hbi,hio->hbo", out, weight) + bias.unsqueeze(1)
            out = self._apply_norm(out, layer_idx)
            out = _activation_forward(self.spec.activation_name, out)

        raw = torch.einsum("hbi,hio->hbo", out, self.output_weight) + self.output_bias.unsqueeze(1)
        mu_raw = raw[..., 0]
        var_raw = raw[..., 1]
        var = F.softplus(var_raw) + float(self.spec.jitter_eps)
        return mu_raw, var

    def batched_artifact(self) -> dict:
        return {
            "format": "batched_de_v1",
            "n_nets": self.n_nets,
            "spec": {
                "input_dim": self.spec.input_dim,
                "hidden_dim": self.spec.hidden_dim,
                "hidden_layers": self.spec.hidden_layers,
                "activation_name": self.spec.activation_name,
                "norm_type": self.spec.norm_type,
                "jitter_eps": self.spec.jitter_eps,
            },
            "state_dict": {k: v.detach().cpu() for k, v in self.state_dict().items()},
        }


