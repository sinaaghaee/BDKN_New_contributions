def array(value):
    if isinstance(value, torch.Tensor): value = value.detach().cpu().numpy()
    return np.asarray(value, dtype=np.float64).reshape(-1)


def gaussian_prediction(mean, variance):
    mean, variance = array(mean), array(variance)
    if not np.isfinite(variance).all() or np.any(variance <= 0):
        raise FloatingPointError("Nonpositive or nonfinite predictive variance")
    scale = np.sqrt(variance)
    return dict(mean=mean, scale=scale, lower=mean-1.959963984540054*scale,
                upper=mean+1.959963984540054*scale, family="gaussian", df=None)



