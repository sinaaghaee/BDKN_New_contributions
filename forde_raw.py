def can_reuse_stage1(artifact, cfg):
    # A repulsive ensemble is a different method even with matching architecture.
    return (artifact.get("method") in ("bdkn", "deep_ensemble")
            and artifact.get("signature") == stage1_signature(cfg))


def main():
    cfg,data,output,device=experiment_setup()
    cfg.update(repulsion_metadata(cfg["repulsion_strength"],cfg["repulsion_bandwidth_floor"],cfg["repulsion_normalization_eps"],cfg["repulsion_location"]))
    x,y,ym,ys=preprocess(data,cfg,device)
    sampler=RepulsionPointSampler(x['x_train'],x['x_grid'],cfg['seed'])
    cfg['repulsion_sampling']=dict(location=cfg['repulsion_location'],domain_raw=[float(data['x_grid'].min()),float(data['x_grid'].max())],
        domain_model=[sampler.low,sampler.high],random_seed=cfg['seed']+1729,redraw='optimizer_step',
        random_count='actual_training_minibatch_size',exclude='all_training_inputs_and_duplicates',
        point_count_multiplier=2 if cfg['repulsion_location']=='combined' else 1)
    (output/'config.json').write_text(json.dumps(cfg,indent=2)+'\n')
    start=time.perf_counter(); history=[]
    ensemble=build_batched_ensemble(cfg["n_nets"],1,cfg["hidden_dim"],cfg["hidden_layers"],
                                    cfg["activation"],cfg["norm_type"],cfg["jitter_eps"],device)
    reused=False
    stage1_training_seconds=None
    if cfg["reuse_stage1"]:
        if METHOD != "deep_ensemble": raise ValueError("Only deep_ensemble accepts --reuse-stage1")
        artifact=torch.load(cfg["reuse_stage1"],map_location=device,weights_only=True)
        if can_reuse_stage1(artifact, cfg):
            ensemble.load_state_dict(artifact["ensemble"]["state_dict"]); reused=True
            history=artifact["history"]
            stage1_training_seconds=artifact.get("training_seconds")
            print("Reusing matching BDKN stage-one ensemble",flush=True)
        else:
            print("Stage-one settings differ; training an independent ensemble",flush=True)
    if not reused:
        optimizer=torch.optim.Adam(ensemble.parameters(),lr=cfg["lr"])
        training_t0=training_clock(device)
        for epoch in range(1,cfg["epochs"]+1):
            ensemble.train(); diagnostics=[]
            for bx,by in _iter_head_batches(x["x_train"],y,cfg["n_nets"],cfg["batch_size"]):
                optimizer.zero_grad()
                repulsion_x=sampler.sample(bx[0],cfg['repulsion_location']) if cfg['repulsion_strength']>0 and cfg['n_nets']>1 else None
                loss,_,diag=training_objective(ensemble,bx,by,cfg,repulsion_x)
                if not torch.isfinite(loss): raise FloatingPointError("Nonfinite training objective")
                loss.backward(); optimizer.step(); diagnostics.append(diag.cpu().numpy())
            values=np.mean(diagnostics,axis=0)
            history.append(dict(stage=1,epoch=epoch,objective=float(values[2]),likelihood=float(values[0]),
                                repulsion=float(values[1]),bandwidth=float(values[3]),distance=float(values[4])))
            if epoch == 1 or epoch % 100 == 0: print(f"{METHOD}: epoch {epoch}/{cfg['epochs']}",flush=True)
    if not reused:
        stage1_training_seconds=training_clock(device)-training_t0
    cfg["_training_seconds"]=stage1_training_seconds
    cfg["_stage1_training_seconds"]=stage1_training_seconds
    cfg["_stage2_training_seconds"]=0.
    cfg["_training_reused"]=reused
    stage1_seconds=time.perf_counter()-start
    torch.save(dict(method=METHOD,signature=stage1_signature(cfg),ensemble=ensemble.batched_artifact(),history=history,
                    training_reused=reused,training_seconds=stage1_training_seconds),output / "stage1.pt")
    with torch.no_grad():
        heads={k:predict_head_outputs(ensemble,v) for k,v in x.items()}
    def de_prediction(key):
        mu,var=predictive_moments_from_head_outputs(*heads[key],cfg["jitter_eps"])
        # Original DE evaluator adds jitter to variance after returning to raw units.
        return gaussian_prediction(mu*ys+ym,var*ys**2+cfg["jitter_eps"])
    rows=[]
    if METHOD == "deep_ensemble":
        rows.append(record_result("deep_ensemble",de_prediction("x_test"),de_prediction("x_grid"),data,output,cfg,stage1_seconds))
    elif METHOD != "bdkn":
        rows.append(record_result(METHOD+"_ensemble",de_prediction("x_test"),de_prediction("x_grid"),data,output,cfg,stage1_seconds))
    if METHOD != "deep_ensemble":
        # Freeze the learned head means; these are the original BDKN basis functions.
        phi={k:build_phi_features(ensemble_mean_features_from_head_outputs(v[0]),x[k],
             cfg["phi_add_identity"],cfg["phi_add_bias"]).to(getattr(torch,cfg["bll_dtype"])) for k,v in heads.items()}
        stage2_t0=training_clock(device)
        train_phi=phi["x_train"]
        design=prepare_bll_design(train_phi,y) if cfg["bll_dtype"] == "float64" else train_phi
        log_sigma=torch.nn.Parameter(torch.tensor(np.log(cfg["Beta_var_prior"]),device=device,dtype=train_phi.dtype))
        if cfg["learn_sigma_p2"]:
            optimizer=torch.optim.Adam([log_sigma],lr=cfg["stage2_lr"])
            for step in range(1,cfg["stage2_steps"]+1):
                optimizer.zero_grad()
                loss=nig_nll_feature(design,y,log_sigma,cfg["alpha0"],cfg["beta0"])
                if not torch.isfinite(loss): raise FloatingPointError("Nonfinite Bayesian-stage objective")
                loss.backward(); optimizer.step()
                history.append(dict(stage=2,epoch=step,objective=float(loss.detach()),likelihood=float(loss.detach()),
                                    repulsion=0.,bandwidth=0.,distance=0.))
        posterior=compute_bll_posterior(design,y,log_sigma.exp().detach(),cfg["alpha0"],cfg["beta0"])
        stage2_training_seconds=training_clock(device)-stage2_t0
        cfg["_stage2_training_seconds"]=stage2_training_seconds
        cfg["_training_seconds"]=stage1_training_seconds+stage2_training_seconds
        def bdk_prediction(key):
            mu,lo,hi=bll_student_t_mu_lo_hi(phi[key],*posterior)
            df=float(2*posterior[2]); q=student_t_dist.ppf(.975,df)
            return dict(mean=array(mu*ys+ym),lower=array(lo*ys+ym),upper=array(hi*ys+ym),
                        scale=array((hi-lo)*ys/(2*q)),family="student_t",df=df)
        rows.append(record_result(METHOD,bdk_prediction("x_test"),bdk_prediction("x_grid"),data,output,cfg,time.perf_counter()-start))
        # Keep posterior arrays inspectable without pickling local Python classes.
        m,p,a,b=posterior
        torch.save(dict(mean=m, precision=p if isinstance(p,torch.Tensor) else dict(right_vectors=p.right_vectors,eigenvalues=p.eigenvalues),
                        alpha=a,beta=b,sigma_p2=log_sigma.exp().detach()),output / "posterior.pt")
    np.savez_compressed(output / "preprocessing.npz", y_mean=ym,y_std=ys,
                        x_train_model=x["x_train"].cpu().numpy())
    (output/"config.json").write_text(json.dumps(cfg,indent=2)+"\n")
    save_history(output,history); finish(output,rows)


if __name__ == "__main__":
    main()
