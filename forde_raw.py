import torch


def whitening_params(x: torch.Tensor, eps: float = 1e-5):
    x_mean = x.mean(dim=0, keepdim=False)
    x_centered = x - x_mean
    sigma = (x_centered.T @ x_centered) / x_centered.shape[0]
    evals, evecs = torch.linalg.eigh(sigma)
    w = evecs @ torch.diag((evals + eps).rsqrt()) @ evecs.T
    return x_mean, w


def whiten(x: torch.Tensor, mean: torch.Tensor, w: torch.Tensor):
    return (x - mean) @ w



