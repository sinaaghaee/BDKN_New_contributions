def build_phi_features(phi_base, x, add_identity=True, add_bias=True):
    feats = [phi_base]
    if add_identity:
        feats.append(x)
    if add_bias:
        feats.append(torch.ones(x.shape[0], 1, device=x.device, dtype=x.dtype))
    return torch.cat(feats, dim=1)


def unnormalize_mu_var(mu_norm, var_norm, y_mean, y_std):
    mu_raw = mu_norm * y_std + y_mean
    var_raw = var_norm * (y_std ** 2)
    return mu_raw, var_raw


def predictive_moments_from_head_outputs(mu_heads: torch.Tensor, var_heads: torch.Tensor, jitter_eps: float):
    mu = mu_heads.mean(dim=0)
    var = (var_heads + mu_heads**2).mean(dim=0) - mu**2
    var = torch.nan_to_num(var, nan=jitter_eps).clamp_min(jitter_eps)
    return mu, var


@torch.no_grad()
def compute_deep_ensemble_nll_rmse_from_head_outputs(
    mu_heads: torch.Tensor,
    var_heads: torch.Tensor,
    y_raw: torch.Tensor,
    y_mean: torch.Tensor,
    y_std: torch.Tensor,
    jitter_eps: float = 1e-6,
):
    mu, var = predictive_moments_from_head_outputs(mu_heads, var_heads, jitter_eps=jitter_eps)
    mu_raw, var_raw = unnormalize_mu_var(mu, var, y_mean, y_std)
    std_raw = torch.sqrt(var_raw + jitter_eps)
    rmse = torch.sqrt(F.mse_loss(mu_raw, y_raw.squeeze())).item()
    nll = -Normal(loc=mu_raw, scale=std_raw).log_prob(y_raw.squeeze()).mean().item()
    return rmse, nll


@torch.no_grad()
def compute_per_head_nll_rmse_from_head_outputs(
    mu_heads: torch.Tensor,
    var_heads: torch.Tensor,
    y_raw: torch.Tensor,
    y_mean: torch.Tensor,
    y_std: torch.Tensor,
    jitter_eps: float = 1e-6,
):
    y_target = y_raw.squeeze().unsqueeze(0)
    mu_raw, var_raw = unnormalize_mu_var(mu_heads, var_heads, y_mean, y_std)
    std_raw = torch.sqrt(var_raw + jitter_eps)
    rmses = torch.sqrt(torch.mean((mu_raw - y_target) ** 2, dim=1))
    nlls = -Normal(loc=mu_raw, scale=std_raw).log_prob(y_target).mean(dim=1)
    return rmses.detach().cpu().tolist(), nlls.detach().cpu().tolist()


def ensemble_mean_features_from_head_outputs(mu_heads: torch.Tensor) -> torch.Tensor:
    return mu_heads.transpose(0, 1)


@torch.no_grad()
def gaussian_mu_lo_hi_from_head_outputs(mu_heads: torch.Tensor, var_heads: torch.Tensor, jitter: float = 1e-12):
    mu_ens, var_ens = predictive_moments_from_head_outputs(mu_heads, var_heads, jitter_eps=jitter)
    sigma = torch.sqrt(var_ens + jitter)
    z975 = 1.959963984540054
    lo = mu_ens - z975 * sigma
    hi = mu_ens + z975 * sigma
    return mu_ens, lo, hi



